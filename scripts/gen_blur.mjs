// Writes src/lib/blur.ts: a tiny blurred data URL per photo in public/img, so every <Image>
// opens on a blur instead of an empty box. Run after adding or replacing a photo.
import { createRequire } from "node:module";
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const require = createRequire(import.meta.url);
const sharp = require(require.resolve("sharp", { paths: [require.resolve("next/package.json")] }));
const dir = "public/img";
const out = {};
for (const f of readdirSync(dir).sort()) {
  if (!/\.(jpe?g|png|webp)$/i.test(f)) continue;
  const buf = await sharp(join(dir, f)).resize(16).blur(1).jpeg({ quality: 60 }).toBuffer();
  out[`/img/${f}`] = `data:image/jpeg;base64,${buf.toString("base64")}`;
}
const body = `// Generated by scripts/gen_blur.mjs. Do not edit by hand.
const BLUR: Record<string, string> = ${JSON.stringify(out, null, 2)};

export function blur(src: string) {
  const blurDataURL = BLUR[src];
  return blurDataURL ? ({ placeholder: "blur", blurDataURL } as const) : {};
}
`;
writeFileSync("src/lib/blur.ts", body);
console.log(Object.keys(out).length, "images");
